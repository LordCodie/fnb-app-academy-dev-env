first_number = int(input("Enter the first number: "))
second_number = int(input("Enter the second number: "))

print(f"Addition: {round(first_number + second_number, 2)}")
print(f"Subtraction: {round(first_number - second_number, 2)}")
print(f"Multiplication: {round(first_number * second_number, 2)}")
print(f"Division: {round(first_number / second_number, 2)}")

print(f"Floor Division: {round(first_number // second_number, 2)}")
print(f"Modulas: {round(first_number % second_number, 2)}")

